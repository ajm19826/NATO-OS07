        private Button btnLoadApps;
        private Button btnUploadPackage;
        private Form2 _mainForm; // Reference to the main OS form

        // Fields to store app info for post-dialog processing
        private AppPackage _appPackageToPin;
        private GroupBox _appGroupBoxToPin;

        public AppInstallerDialog(Form2 mainForm)
        {
            InitializeComponent();
            _mainForm = mainForm;
            this.Text = "App Installer";
            this.Size = new Size(800, 600);
            this.StartPosition = FormStartPosition.CenterScreen;

