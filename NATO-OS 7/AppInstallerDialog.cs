            txtAppUrl = new TextBox { Location = new Point(10, 30), Width = 400, Text = "https://ajm19826.github.io/NATO-OS-Pkgs/pkgs/apps.json" }; // Default URL for testing
            btnLoadApps = new Button { Text = "Load Apps from URL", Location = new Point(420, 28), AutoSize = true };
            btnUploadPackage = new Button { Text = "Upload Package (.npkg)", Location = new Point(550, 28), AutoSize = true };

            flowLayoutPanelApps = new FlowLayoutPanel
            {
                Location = new Point(10, 70),
                Size = new Size(760, 500),
