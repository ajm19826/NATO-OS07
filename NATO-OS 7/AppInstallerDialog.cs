        private async void BtnLoadApps_Click(object sender, EventArgs e)
        {
            string url = txtAppUrl.Text.Trim();
            if (string.IsNullOrEmpty(url))
            {
                MessageBox.Show("Please enter an App URL.", "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
                return;
            }

            try
            {
                using (HttpClient client = new HttpClient())
                {
                    // Ensure the URL ends with a slash if it's a directory, or points directly to a JSON file
                    if (!url.EndsWith("/"))
                    {
                        url += "/"; // Assume it's a directory containing apps.json
                    }
                    string jsonUrl = url + "apps.json"; // Assuming apps metadata is in apps.json

                    string jsonContent = await client.GetStringAsync(jsonUrl);
                    List<AppPackage> availableApps = JsonConvert.DeserializeObject<List<AppPackage>>(jsonContent);

                    DisplayAvailableApps(availableApps);
                }
            }
            catch (HttpRequestException httpEx)
            {
                MessageBox.Show($"Error fetching app list from URL: {httpEx.Message}. Please check the URL and your internet connection.", "Network Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            catch (Newtonsoft.Json.JsonException jsonEx) // Specify Newtonsoft.Json.JsonException
            {
                MessageBox.Show($"Error parsing app list: {jsonEx.Message}. The JSON format might be incorrect.", "Data Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            catch (Exception ex)
            {
                MessageBox.Show($"An unexpected error occurred: {ex.Message}", "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void DisplayAvailableApps(List<AppPackage> apps)
        {
            flowLayoutPanelApps.Controls.Clear(); // Clear existing apps

            if (apps == null || apps.Count == 0)
            {
                Label noAppsLabel = new Label { Text = "No apps found at this URL.", AutoSize = true, ForeColor = Color.Red };
                flowLayoutPanelApps.Controls.Add(noAppsLabel);
                return;
            }

            foreach (var app in apps)
            {
                GroupBox appGroupBox = CreateAppGroupBox(app);
                flowLayoutPanelApps.Controls.Add(appGroupBox);
            }
        }

        private GroupBox CreateAppGroupBox(AppPackage app)
        {
            GroupBox groupBox = new GroupBox
            {
                Text = app.AppName,
                Size = new Size(740, 100),
                Margin = new Padding(5),
                Tag = app // Store the entire AppPackage object in the Tag for easy retrieval
            };

            Label lblDescription = new Label
            {
                Text = app.AppDescription,
                Location = new Point(10, 20),
                AutoSize = true,
                MaximumSize = new Size(720, 0) // Allow multiline description
            };

            Button btnInstall = new Button
            {
                Text = "Install App",
                Location = new Point(10, 60),
                AutoSize = true
            };
            btnInstall.Click += (sender, e) => InstallApp(app);

            groupBox.Controls.Add(lblDescription);
            groupBox.Controls.Add(btnInstall);

            return groupBox;
        }

        private void InstallApp(AppPackage app)
        {
            try
            {
                // Before loading, perform a basic virus scan on the app code
                if (_mainForm.ScanAppCodeForViruses(app.AppCode))
                {
                    MessageBox.Show("Potential malicious code detected in the app. Installation aborted.", "Security Warning", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                    return;
                }

                // Load the app and get a reference to the created GroupBox
                GroupBox installedAppGroupBox = _mainForm.LoadAppFromPackage(app);

                // If the app was successfully loaded, store info for pinning after dialog closes
                if (installedAppGroupBox != null)
                {
                    _appPackageToPin = app;
                    _appGroupBoxToPin = installedAppGroupBox;
                    MessageBox.Show($"App '{app.AppName}' installed and loaded onto the OS!", "Installation Complete", MessageBoxButtons.OK, MessageBoxIcon.Information);
                    this.Close(); // Close the installer after installation
                }
                else
                {
                    MessageBox.Show($"Failed to install app '{app.AppName}'. See console for details.", "Installation Failed", MessageBoxButtons.OK, MessageBoxIcon.Error);
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Error installing app: {ex.Message}", "Installation Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void BtnUploadPackage_Click(object sender, EventArgs e)
        {
            using (OpenFileDialog openFileDialog = new OpenFileDialog())
            {
                openFileDialog.Filter = "NATO OS Package Files (*.npkg)|*.npkg|All Files (*.*)|*.*";
                openFileDialog.Title = "Select an App Package (.npkg) to Upload";

                if (openFileDialog.ShowDialog() == DialogResult.OK)
                {
                    try
                    {
                        string filePath = openFileDialog.FileName;
                        string jsonContent = File.ReadAllText(filePath);
                        AppPackage loadedPackage = JsonConvert.DeserializeObject<AppPackage>(jsonContent);

                        if (loadedPackage != null)
                        {
                            // Before loading, perform a basic virus scan on the app code
                            if (_mainForm.ScanAppCodeForViruses(loadedPackage.AppCode))
                            {
                                MessageBox.Show("Potential malicious code detected in the app. Loading aborted.", "Security Warning", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                                return;
                            }

                            // Load the app and get a reference to the created GroupBox
                            GroupBox installedAppGroupBox = _mainForm.LoadAppFromPackage(loadedPackage);

                            // If the app was successfully loaded, store info for pinning after dialog closes
                            if (installedAppGroupBox != null)
                            {
                                _appPackageToPin = loadedPackage;
                                _appGroupBoxToPin = installedAppGroupBox;
                                MessageBox.Show($"Package '{loadedPackage.AppName}' loaded successfully!", "Package Loaded", MessageBoxButtons.OK, MessageBoxIcon.Information);
                                this.Close();
                            }
                            else
                            {
                                MessageBox.Show($"Failed to load package '{loadedPackage.AppName}'. See console for details.", "Load Failed", MessageBoxButtons.OK, MessageBoxIcon.Error);
                            }
                        }
                        else
                        {
                            MessageBox.Show("Failed to load package. The file might be corrupted or in an invalid format.", "Load Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
                        }
                    }
                    catch (Newtonsoft.Json.JsonException jsonEx) // Specify Newtonsoft.Json.JsonException
                    {
                        MessageBox.Show($"Error parsing package file: {jsonEx.Message}. The file might be corrupted or in an invalid JSON format.", "File Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
                    }
                    catch (Exception ex)
                    {
                        MessageBox.Show($"An error occurred while uploading the package: {ex.Message}", "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
                    }
                }
            }
        }

        // Public properties to expose the app info after the dialog closes
